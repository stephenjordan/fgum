#!/usr/bin/env python3
"""Optional finite-size Gallager block-failure experiments, using only the stdlib.

The first layer consists of ``blocks`` fixed blocks, each containing ``D``
columns.  Each of the other ``k - 1`` layers is an independently sampled uniform
partition of those columns into rows of size ``D``.  A failed first-layer block
includes all its columns in the matrix whose rank is measured.

By default block failures are independent Bernoulli events.  The optional
``fixed-count`` model instead samples a uniformly chosen set of a prescribed
size; this is a different finite-size ensemble.  Neither experiment is a proof
of an asymptotic threshold.  The existing interval certificate supplies only
the reference threshold and, when rates are omitted, nearby sampling rates.

The column sampler, integer-XOR elimination, and singleton-row peeling adapt the
corresponding routines in the recovered original reproducibility archive.  The
old threshold solvers, counting formulas, and first-moment code are not used.
"""

from __future__ import annotations

import argparse
from collections import defaultdict, deque
import csv
from dataclasses import asdict, dataclass
from fractions import Fraction
import hashlib
import io
import json
import math
from pathlib import Path
import platform
import random
import sys
from typing import Iterable, Sequence


SUPPORTED_PAIRS = tuple((k, D) for k in range(3, 8) for D in range(k + 1, 9))
ERASURE_MODELS = ("bernoulli", "fixed-count")
SEED_SCHEME = "fgum-exact-rank-trial-v1"
RUN_SCHEMA = "fgum-exact-rank-experiments-v1"
DEFAULT_OUTDIR = Path(__file__).resolve().parent / "output"


def _integer(value: int, name: str, minimum: int | None = None) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise ValueError(f"{name} must be an integer")
    if minimum is not None and value < minimum:
        raise ValueError(f"{name} must be at least {minimum}")
    return value


def _validate_pair(k: int, D: int) -> None:
    _integer(k, "k")
    _integer(D, "D")
    if (k, D) not in SUPPORTED_PAIRS:
        raise ValueError("supported pairs satisfy 3 <= k < D <= 8 (15 pairs)")


def _rate(value: float) -> float:
    if isinstance(value, bool):
        raise ValueError("rate must be a finite number in [0, 1]")
    try:
        rate = float(value)
    except (TypeError, ValueError, OverflowError) as error:
        raise ValueError("rate must be a finite number in [0, 1]") from error
    if not math.isfinite(rate) or not 0 <= rate <= 1:
        raise ValueError("rate must be a finite number in [0, 1]")
    return 0.0 if rate == 0 else rate  # Canonicalize signed zero for seeds.


def _model(erasure_model: str) -> None:
    if erasure_model not in ERASURE_MODELS:
        raise ValueError("erasure_model must be 'bernoulli' or 'fixed-count'")


def _column_supports(
    columns: Iterable[Sequence[int]], nrows: int | None = None
) -> tuple[tuple[int, ...], ...]:
    if nrows is not None:
        _integer(nrows, "nrows", 0)
    result = []
    for column in columns:
        rows = tuple(column)
        for row in rows:
            _integer(row, "row index", 0)
            if nrows is not None and row >= nrows:
                raise ValueError("row index is outside the matrix")
        if len(set(rows)) != len(rows):
            raise ValueError("a column support cannot repeat a row index")
        result.append(rows)
    return tuple(result)


def sample_gallager_columns(
    k: int, D: int, blocks: int, rng: random.Random
) -> list[tuple[int, ...]]:
    """Return all D*blocks column supports in a k*blocks-row binary matrix.

    Row indices ``layer * blocks .. (layer + 1) * blocks - 1`` form one
    layer.  Column j belongs to first-layer row j//D.  Each later layer is
    independently generated by shuffling all column indices and assigning
    successive groups of D indices to rows.  Every row has exactly D ones.
    """
    _validate_pair(k, D)
    _integer(blocks, "blocks", 1)
    total_columns = D * blocks
    supports = [[j // D] for j in range(total_columns)]
    for layer in range(1, k):
        permutation = list(range(total_columns))
        rng.shuffle(permutation)
        for position, column in enumerate(permutation):
            supports[column].append(layer * blocks + position // D)
    return [tuple(rows) for rows in supports]


def select_failed_blocks(
    blocks: int,
    rate: float,
    rng: random.Random,
    erasure_model: str = "bernoulli",
) -> tuple[int, ...]:
    """Sample failed block indices, with Bernoulli failures as the default.

    Fixed-count rounds blocks*rate to the nearest integer, with ties upward,
    using the exact decimal represented by str(float(rate)); it then samples
    that many distinct blocks uniformly.  The result is sorted in both models.
    """
    _integer(blocks, "blocks", 1)
    rate = _rate(rate)
    _model(erasure_model)
    if erasure_model == "bernoulli":
        return tuple(block for block in range(blocks) if rng.random() < rate)
    count = math.floor(blocks * Fraction(str(rate)) + Fraction(1, 2))
    return tuple(sorted(rng.sample(range(blocks), count)))


def gf2_column_rank(
    columns: Iterable[Sequence[int]], nrows: int | None = None
) -> int:
    """Compute exact binary rank from column supports by integer XOR.

    Empty columns are allowed.  Row indices must be distinct nonnegative
    integers within each column, and less than nrows if nrows is supplied.
    Inputs are not modified; no numerical rank tolerance is involved.
    """
    basis: dict[int, int] = {}
    for rows in _column_supports(columns, nrows):
        value = 0
        for row in rows:
            value |= 1 << row
        while value:
            pivot = value.bit_length() - 1
            previous = basis.get(pivot)
            if previous is None:
                basis[pivot] = value
                break
            value ^= previous
    return len(basis)


@dataclass(frozen=True)
class PeelResult:
    surviving_column_indices: tuple[int, ...]
    surviving_row_indices: tuple[int, ...]
    peeled_columns: int

    @property
    def core_columns(self) -> int:
        return len(self.surviving_column_indices)

    @property
    def core_rows(self) -> int:
        return len(self.surviving_row_indices)


def peel_core(columns: Iterable[Sequence[int]], nrows: int) -> PeelResult:
    """Repeatedly remove a singleton row's unique column, including cascades.

    Return surviving column indices relative to the input, and nonzero row
    indices relative to the original matrix.  All surviving nonzero rows have
    weight at least two.  Zero columns remain because they carry nullity.
    The inputs are not mutated.  A queue changes the order of deletions, not
    the final surviving set of columns.
    """
    supports = _column_supports(columns, nrows)
    degree = [0] * nrows
    xor_id = [0] * nrows
    for column, rows in enumerate(supports):
        token = column + 1
        for row in rows:
            degree[row] += 1
            xor_id[row] ^= token
    alive = [True] * len(supports)
    queue = deque(row for row, weight in enumerate(degree) if weight == 1)
    removed = 0
    while queue:
        row = queue.popleft()
        if degree[row] != 1:
            continue
        column = xor_id[row] - 1
        if not 0 <= column < len(supports) or not alive[column]:
            raise RuntimeError("singleton-row peeling bookkeeping is inconsistent")
        alive[column] = False
        removed += 1
        for incident_row in supports[column]:
            degree[incident_row] -= 1
            xor_id[incident_row] ^= column + 1
            if degree[incident_row] == 1:
                queue.append(incident_row)
    if any(weight == 1 or weight < 0 for weight in degree):
        raise RuntimeError("peeling did not leave valid residual row weights")
    return PeelResult(
        surviving_column_indices=tuple(i for i, present in enumerate(alive) if present),
        surviving_row_indices=tuple(i for i, weight in enumerate(degree) if weight > 0),
        peeled_columns=removed,
    )


def _hash_seed(payload: dict) -> int:
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("ascii")
    return int.from_bytes(hashlib.sha256(encoded).digest(), "big")


def derive_trial_seed(
    base_seed: int,
    k: int,
    D: int,
    blocks: int,
    rate: float,
    trial_index: int,
    erasure_model: str = "bernoulli",
) -> int:
    """Hash the trial's parameters; grid order and grid size do not enter."""
    _integer(base_seed, "base_seed")
    _validate_pair(k, D)
    _integer(blocks, "blocks", 1)
    _integer(trial_index, "trial_index", 0)
    rate = _rate(rate)
    _model(erasure_model)
    return _hash_seed({
        "scheme": SEED_SCHEME,
        "base_seed": base_seed,
        "k": k,
        "D": D,
        "blocks": blocks,
        "rate_hex": rate.hex(),
        "trial_index": trial_index,
        "erasure_model": erasure_model,
    })


def derive_stream_seed(trial_seed: int, stream: str) -> int:
    """Separate the matrix and block-failure random streams for one trial."""
    _integer(trial_seed, "trial_seed", 0)
    if stream not in ("matrix", "failures"):
        raise ValueError("stream must be 'matrix' or 'failures'")
    return _hash_seed({
        "scheme": SEED_SCHEME + "-stream",
        "trial_seed": trial_seed,
        "stream": stream,
    })


@dataclass(frozen=True)
class TrialResult:
    matrix_seed: int
    failure_seed: int
    failed_blocks: int
    actual_failed_fraction: float
    columns: int
    nonzero_rows: int
    rank: int
    nullity: int
    full_column_rank: bool
    core_columns: int
    core_rows: int
    core_rank: int
    core_nullity: int
    peeled_columns: int


def run_trial(
    k: int,
    D: int,
    blocks: int,
    rate: float,
    trial_seed: int,
    erasure_model: str = "bernoulli",
) -> TrialResult:
    """Sample a fresh matrix and failures; check rank against peeling exactly."""
    _validate_pair(k, D)
    _integer(blocks, "blocks", 1)
    rate = _rate(rate)
    _model(erasure_model)
    matrix_seed = derive_stream_seed(trial_seed, "matrix")
    failure_seed = derive_stream_seed(trial_seed, "failures")
    full_columns = sample_gallager_columns(k, D, blocks, random.Random(matrix_seed))
    failed = select_failed_blocks(blocks, rate, random.Random(failure_seed), erasure_model)
    columns = [full_columns[block * D + offset] for block in failed for offset in range(D)]
    nrows = k * blocks
    rank = gf2_column_rank(columns, nrows)
    nullity = len(columns) - rank
    core = peel_core(columns, nrows)
    core_rank = gf2_column_rank(
        [columns[index] for index in core.surviving_column_indices], nrows
    )
    core_nullity = core.core_columns - core_rank
    if nullity != core_nullity or rank != core.peeled_columns + core_rank:
        raise RuntimeError("exact full-matrix and residual-core ranks violate peeling invariance")
    return TrialResult(
        matrix_seed=matrix_seed,
        failure_seed=failure_seed,
        failed_blocks=len(failed),
        actual_failed_fraction=len(failed) / blocks,
        columns=len(columns),
        nonzero_rows=len({row for support in columns for row in support}),
        rank=rank,
        nullity=nullity,
        full_column_rank=(nullity == 0),
        core_columns=core.core_columns,
        core_rows=core.core_rows,
        core_rank=core_rank,
        core_nullity=core_nullity,
        peeled_columns=core.peeled_columns,
    )


def run_grid(
    k: int,
    D: int,
    blocks: Sequence[int],
    rates: Sequence[float],
    trials: int,
    base_seed: int,
    erasure_model: str = "bernoulli",
) -> list[dict]:
    """Return raw trial rows on a sorted, deduplicated parameter grid."""
    _validate_pair(k, D)
    _integer(trials, "trials", 1)
    _integer(base_seed, "base_seed")
    _model(erasure_model)
    sizes = sorted({_integer(size, "blocks", 1) for size in blocks})
    probabilities = sorted({_rate(rate) for rate in rates})
    if not sizes or not probabilities:
        raise ValueError("blocks and rates must each contain at least one value")
    rows = []
    for size in sizes:
        for rate in probabilities:
            for trial_index in range(trials):
                seed = derive_trial_seed(base_seed, k, D, size, rate, trial_index, erasure_model)
                result = run_trial(k, D, size, rate, seed, erasure_model)
                rows.append({
                    "k": k,
                    "D": D,
                    "blocks": size,
                    "total_columns": D * size,
                    "total_rows": k * size,
                    "rate": rate,
                    "rate_hex": rate.hex(),
                    "erasure_model": erasure_model,
                    "trial_index": trial_index,
                    "base_seed": base_seed,
                    "trial_seed": seed,
                    **asdict(result),
                })
    return rows


MEAN_FIELDS = (
    "failed_blocks", "actual_failed_fraction", "columns", "nonzero_rows", "rank",
    "nullity", "core_columns", "core_rows", "core_rank", "core_nullity", "peeled_columns",
)
GROUP_FIELDS = ("k", "D", "blocks", "rate_hex", "erasure_model", "base_seed")


def summarize_trials(rows: Sequence[dict]) -> list[dict]:
    """Summarize in-memory raw rows; fractions are empirical trial frequencies."""
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for row in rows:
        groups[tuple(row[field] for field in GROUP_FIELDS)].append(row)
    summaries = []
    ordered_keys = sorted(groups, key=lambda key: (
        key[0], key[1], key[2], float.fromhex(key[3]), key[4], key[5]
    ))
    for key in ordered_keys:
        sample = groups[key]
        first = sample[0]
        successes = sum(row["full_column_rank"] for row in sample)
        summary = {
            field: first[field] for field in (
                "k", "D", "blocks", "total_columns", "total_rows", "rate", "rate_hex",
                "erasure_model", "base_seed",
            )
        }
        summary.update({
            "trials": len(sample),
            "full_column_rank_trials": successes,
            "full_column_rank_fraction": successes / len(sample),
        })
        for field in MEAN_FIELDS:
            summary["mean_" + field] = math.fsum(row[field] for row in sample) / len(sample)
        summaries.append(summary)
    return summaries


def load_reference_certificate(k: int, D: int) -> dict:
    """Read the existing certificate's threshold and identity, without solving.

    This validates only the schema, pair, status, and interval structure needed
    by these experiments.  Certificate verification remains the responsibility
    of the separate interval replay tools; no such tool is imported here.
    """
    _validate_pair(k, D)
    path = Path(__file__).resolve().parents[1] / "results" / f"certificate_k{k}_D{D}.json"
    raw = path.read_bytes()
    data = json.loads(raw)
    if (
        data.get("k") != k or data.get("D") != D or data.get("status") != "passed"
        or data.get("schema") != "fgum-core-interval-certificate-v1"
    ):
        raise ValueError(f"unexpected reference certificate identity or status: {path}")
    bounds = data["summary"]["e_core"]
    lower, upper = Fraction(bounds["lower"]), Fraction(bounds["upper"])
    if not 0 <= lower <= upper <= 1:
        raise ValueError("reference e_core interval is invalid")
    return {
        "path": f"reproducibility/results/{path.name}",
        "sha256": hashlib.sha256(raw).hexdigest(),
        "schema": data["schema"],
        "status": data["status"],
        "k": k,
        "D": D,
        "e_core": {"lower": bounds["lower"], "upper": bounds["upper"]},
        "e_core_midpoint_float": float((lower + upper) / 2),
        "use": "reference only; this experiment does not rerun interval verification",
    }


def default_rates(reference: dict) -> list[float]:
    """Use the reference midpoint and offsets of +/-0.02, clipped to [0,1]."""
    bounds = reference["e_core"]
    midpoint = (Fraction(bounds["lower"]) + Fraction(bounds["upper"])) / 2
    return sorted({float(min(Fraction(1), max(Fraction(0), midpoint + offset)))
                   for offset in (-Fraction(1, 50), Fraction(0), Fraction(1, 50))})


def _csv_bytes(rows: Sequence[dict]) -> bytes:
    if not rows:
        raise ValueError("cannot write an empty experiment table")
    buffer = io.StringIO(newline="")
    writer = csv.DictWriter(buffer, fieldnames=list(rows[0]), lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return buffer.getvalue().encode("utf-8")


def _check_output_paths(outdir: Path) -> None:
    if outdir.exists() and not outdir.is_dir():
        raise ValueError(f"output location is not a directory: {outdir}")
    for name in ("trials.csv", "summary.csv", "run.json"):
        path = outdir / name
        if path.exists() or path.is_symlink():
            raise FileExistsError(f"refusing to overwrite existing output: {path}")


def write_outputs(outdir: Path, rows: Sequence[dict], metadata: dict) -> None:
    """Write new outputs exclusively; never replace or remove existing files."""
    outdir = Path(outdir)
    _check_output_paths(outdir)
    raw = _csv_bytes(rows)
    summary_rows = summarize_trials(rows)
    summary = _csv_bytes(summary_rows)
    metadata = dict(metadata)
    metadata["output_files"] = {
        "trials.csv": {"rows": len(rows), "sha256": hashlib.sha256(raw).hexdigest()},
        "summary.csv": {
            "rows": len(summary_rows),
            "sha256": hashlib.sha256(summary).hexdigest(),
        },
    }
    manifest = (json.dumps(metadata, indent=2, sort_keys=True, allow_nan=False) + "\n").encode("utf-8")
    outdir.mkdir(parents=True, exist_ok=True)
    # Exclusive creation also prevents a concurrent writer from being overwritten.
    for name, content in (("trials.csv", raw), ("summary.csv", summary), ("run.json", manifest)):
        with (outdir / name).open("xb") as output:
            output.write(content)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--k", type=int, required=True, help="number of row layers")
    parser.add_argument("--D", type=int, required=True, help="full row weight; 3 <= k < D <= 8")
    parser.add_argument("--blocks", type=int, nargs="+", default=[100], metavar="B",
                        help="number b=m/D of FGUM blocks / rows per layer (default: 100)")
    parser.add_argument("--rates", type=float, nargs="+", metavar="E",
                        help="block-failure probabilities (default: frozen e_core midpoint and +/-0.02)")
    parser.add_argument("--trials", type=int, default=20, help="independent trials per grid point (default: 20)")
    parser.add_argument("--seed", type=int, default=0, help="base seed (default: 0)")
    parser.add_argument("--erasure-model", choices=ERASURE_MODELS, default="bernoulli",
                        help="independent block failures or uniformly sampled fixed count (default: bernoulli)")
    parser.add_argument("--outdir", type=Path, default=DEFAULT_OUTDIR,
                        help="new output directory (default: output/ alongside this script); never overwrite")
    args = parser.parse_args(argv)
    try:
        _validate_pair(args.k, args.D)
        _integer(args.trials, "trials", 1)
        sizes = sorted({_integer(size, "blocks", 1) for size in args.blocks})
        supplied_rates = None if args.rates is None else sorted({_rate(rate) for rate in args.rates})
        reference = load_reference_certificate(args.k, args.D)
        rates = default_rates(reference) if supplied_rates is None else supplied_rates
        _check_output_paths(args.outdir)
        rows = run_grid(args.k, args.D, sizes, rates, args.trials, args.seed, args.erasure_model)
        script = Path(__file__).resolve()
        metadata = {
            "schema": RUN_SCHEMA,
            "purpose": "optional finite-size exact-rank diagnostics; not a threshold certificate",
            "parameters": {
                "k": args.k, "D": args.D, "blocks": sizes, "rates": rates,
                "rates_hex": [rate.hex() for rate in rates], "trials_per_point": args.trials,
                "base_seed": args.seed, "erasure_model": args.erasure_model,
                "rate_source": "frozen e_core midpoint +/-0.02, clipped to [0,1]" if supplied_rates is None else "explicit --rates",
                "total_trials": len(rows),
            },
            "sampling": {
                "matrix": "fresh independent Gallager matrix per trial; fixed first layer and independently uniform partitions in other layers",
                "blocks": "b=m/D; each failed first-layer block includes all D columns in the rank calculation",
                "failures": "independent Bernoulli events with probability rate" if args.erasure_model == "bernoulli" else "uniform subset of floor(b*rate+1/2) blocks, using Fraction(str(float(rate))); ties upward",
                "random_generator": "Python random.Random (Mersenne Twister); separate matrix and failure streams",
            },
            "seeding": {
                "scheme": SEED_SCHEME,
                "trial": "SHA256 of compact, ASCII, key-sorted JSON with scheme,base_seed,k,D,blocks,rate_hex,trial_index,erasure_model; big-endian digest integer",
                "streams": "SHA256 of analogous JSON with scheme=trial scheme+'-stream',trial_seed,stream ('matrix' or 'failures')",
                "trial_index": "zero-based within each grid point",
                "record": "base_seed, trial_seed, matrix_seed, failure_seed in every trials.csv row",
                "grid_order": "sorted and deduplicated; neither grid order nor trial count enters a trial seed",
            },
            "verification": {
                "rank": "exact binary Gaussian elimination using Python integer XOR",
                "peeling": "iterative singleton-row deletion, including newly created singletons",
                "every_trial_checks": ["nullity == core_nullity", "rank == peeled_columns + core_rank"],
                "core_rows": "number of nonzero residual rows; zero rows discarded",
                "zero_columns": "retained by peeling and included in column nullity",
                "empty_matrix": "zero columns has rank 0, nullity 0, and full column rank",
            },
            "python": {
                "version": platform.python_version(), "implementation": platform.python_implementation(),
                "full_version": sys.version,
            },
            "script": {
                "path": "reproducibility/experiments/exact_rank_experiments.py",
                "sha256": hashlib.sha256(script.read_bytes()).hexdigest(),
            },
            "reference_certificate": reference,
        }
        write_outputs(args.outdir, rows, metadata)
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.error(str(error))
    print(f"Wrote {len(rows)} trials and {len(sizes) * len(rates)} summaries to {args.outdir.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
